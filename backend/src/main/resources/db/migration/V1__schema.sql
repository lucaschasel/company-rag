CREATE TABLE app_user (
 id VARCHAR(36) PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE knowledge_base (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, description VARCHAR(2000) NOT NULL,
 owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE kb_member (
 kb_id VARCHAR(36) NOT NULL REFERENCES knowledge_base(id) ON DELETE CASCADE,
 user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, PRIMARY KEY(kb_id,user_id)
);
CREATE TABLE document (
 id VARCHAR(36) PRIMARY KEY, kb_id VARCHAR(36) NOT NULL REFERENCES knowledge_base(id) ON DELETE CASCADE,
 name VARCHAR(255) NOT NULL, storage_key VARCHAR(80) NOT NULL, size_bytes BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL, error_message VARCHAR(1000), chunk_count INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_document_kb ON document(kb_id);
CREATE TABLE chunk (
 id VARCHAR(36) PRIMARY KEY, document_id VARCHAR(36) NOT NULL REFERENCES document(id) ON DELETE CASCADE,
 ordinal INT NOT NULL, content TEXT NOT NULL, embedding TEXT, embedding_model VARCHAR(255), UNIQUE(document_id,ordinal)
);
CREATE TABLE audit_event (
 id VARCHAR(36) PRIMARY KEY, username VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL,
 resource_id VARCHAR(100) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
