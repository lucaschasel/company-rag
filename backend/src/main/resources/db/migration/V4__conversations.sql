CREATE TABLE conversation (
  id VARCHAR(36) PRIMARY KEY,
  user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_conversation_user ON conversation(user_id, updated_at DESC);

CREATE TABLE conversation_message (
  id VARCHAR(36) PRIMARY KEY,
  conversation_id VARCHAR(36) NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  role VARCHAR(16) NOT NULL,
  content TEXT NOT NULL,
  mode VARCHAR(20),
  citations TEXT,
  error VARCHAR(1000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_message_conversation ON conversation_message(conversation_id, seq);
